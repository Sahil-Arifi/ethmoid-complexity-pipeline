import { expect, test } from "@playwright/test";

test("grouped study selection preserves drafts and isolates each series result", async ({ page }) => {
  const errors: string[] = [];
  const started: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", request => { if (request.method() === "POST" && request.url().endsWith("/count-runs")) started.push(request.url()); });
  await page.addInitScript(() => localStorage.setItem("ethmoid:first-run-guide", "2"));
  await page.goto("/");
  const row = page.getByTestId("study-synthetic-study");
  await expect(row).toHaveCount(1);
  await expect(row).toContainText("3 series");
  const select = row.getByRole("combobox", { name: "Series for Case900" });
  await expect(select).toHaveValue("synthetic-thin");
  await expect(select.getByRole("option").first()).toHaveText(/Series007.*Recommended/);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(select).toBeVisible();
  await expect(row.getByRole("button", { name: "Open series" })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
  await page.setViewportSize({ width: 1280, height: 900 });
  await select.selectOption("synthetic-scout");
  await expect(row).toContainText("This is a scout image, not a three-dimensional CT volume.");
  await expect(row.getByRole("button", { name: "Unavailable" })).toBeDisabled();
  await select.selectOption("synthetic-thin");
  await row.getByRole("button", { name: "Open series" }).click();
  await expect(page.getByRole("heading", { name: "Case900 · Series007" })).toBeVisible();
  await expect(page.getByTestId("total-count")).toHaveCount(0);
  expect(started).toHaveLength(0);
  await page.getByRole("button", { name: "Run automatic count" }).click();
  await expect(page.getByTestId("total-count")).toHaveText("2");
  await page.getByRole("button", { name: "Add cell" }).click();
  const originalUrl = page.url();
  const workspaceSeries = page.getByRole("combobox", { name: "Series to open" });
  await workspaceSeries.selectOption("synthetic-thick");
  page.once("dialog", dialog => dialog.dismiss());
  await page.getByRole("button", { name: "Open selected series" }).click();
  await expect(page).toHaveURL(originalUrl);
  await expect(workspaceSeries).toHaveValue("synthetic-thin");
  const unchanged = await page.request.get("/api/studies");
  expect((await unchanged.json()).studies[0].selected_series_id).toBe("synthetic-thin");
  await workspaceSeries.selectOption("synthetic-thick");
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "Open selected series" }).click();
  await expect(page.getByRole("heading", { name: "Case900 · Series001" })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Add a cell" })).toHaveCount(0);
  await expect(page.getByTestId("total-count")).toHaveCount(0);
  await expect(page.getByRole("button", { name: /#300/ })).toHaveCount(0);
  await expect(page.getByText(/outside the thin native CT protocol \(slice thickness 2.5 mm\)/)).toBeVisible();
  expect(started).toHaveLength(1);
  await page.getByRole("button", { name: "Run automatic count" }).click();
  await expect(page.getByTestId("total-count")).toHaveText("2");
  expect(started).toHaveLength(2);
  expect(new Set(started).size).toBe(2);
  await page.getByRole("button", { name: "Cases", exact: true }).click();
  await expect(select).toHaveValue("synthetic-thick");
  await expect(row).toContainText("Count complete · L 1 / R 1 / Total 2");
  await page.reload();
  await expect(select).toHaveValue("synthetic-thick");
  await select.selectOption("synthetic-thin");
  await row.getByRole("button", { name: "Open series" }).click();
  await expect(page.getByRole("heading", { name: "Case900 · Series007" })).toBeVisible();
  await expect(page.getByTestId("total-count")).toHaveText("2");
  expect(started).toHaveLength(2);
  await expect(page.locator(".viewer-error")).toHaveCount(0);
  expect(errors).toEqual([]);
});
